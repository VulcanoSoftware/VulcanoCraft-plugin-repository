class I18n {
    constructor() {
        this.currentLang = localStorage.getItem('user_language') || 'nl';
    }

    get lang() {
        return this.currentLang;
    }

    setLanguage(lang, saveToAccount = false) {
        if (!translations[lang]) lang = 'nl';
        this.currentLang = lang;
        localStorage.setItem('user_language', lang);
        document.documentElement.lang = lang;

        if (saveToAccount) {
            fetch('/api/user/language', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ language: lang })
            }).catch(err => console.error('Failed to save language to account:', err));
        }

        this.applyTranslations();
    }

    t(key, params = {}) {
        let text = (translations[this.currentLang] && translations[this.currentLang][key]) ||
                   (translations['nl'] && translations['nl'][key]) || key;
        Object.keys(params).forEach(p => {
            text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
        });
        return text;
    }

    applyTranslations() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            el.textContent = this.t(key);
        });

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.placeholder = this.t(key);
        });

        document.querySelectorAll('[data-i18n-title]').forEach(el => {
            const key = el.getAttribute('data-i18n-title');
            el.title = this.t(key);
        });

        const currentFlag = document.getElementById('currentLanguageFlag');
        const currentText = document.getElementById('currentLanguageText');
        if (currentFlag) {
            currentFlag.src = this.currentLang === 'en' ? 'images/flags/gb.svg' : 'images/flags/nl.svg';
            currentFlag.alt = this.currentLang.toUpperCase();
        }
        if (currentText) {
            currentText.textContent = this.currentLang === 'en' ? 'English' : 'Nederlands';
        }
    }
}

export const i18n = new I18n();
export default i18n;
